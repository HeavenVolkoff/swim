//! Windows Installer compound-file stream name compression (`CompressStreamName`).
//!
//! Why this exists:
//! The Compound File Binary Format (MS-CFB) limits directory entry names to 31
//! UTF-16 code units (plus a NUL terminator) and forbids characters `0x00`..`0x1F`,
//! `/`, `\`, `:`, and `!`. However, Windows Installer table and stream names can
//! be up to 62 characters long (such as `InstallExecuteSequence` or
//! `Icon.ProductIcon.ico`).
//!
//! To fit longer names into 31 UTF-16 units and distinguish database table
//! streams from raw binary streams, Windows Installer mangles stream names using
//! a 6-bit base-64-like alphabet (`0-9`, `A-Z`, `a-z`, `.`, `_`) mapped into the
//! Unicode Private Use / CJK Unified Ideographs range (`U+3800`..`U+4840`):
//! - Each pair of adjacent alphabet characters `(c0, c1)` is packed into a single
//!   UTF-16 code unit: `0x3800 + sixBit(c0) + (sixBit(c1) << 6)`.
//! - A trailing unpaired alphabet character becomes `0x4800 + sixBit(c0)`.
//! - Database table streams are prefixed with the marker code unit `U+4840` so
//!   their names never collide with embedded binary or cabinet streams.
//!
//! Every stream name generated by `swim` uses only this 64-character alphabet,
//! so characters outside it are rejected with `error.InvalidStreamName`.

const std = @import("std");
const Allocator = std.mem.Allocator;

/// Prefix code unit prepended to all MSI database table stream names (`_Tables`,
/// `File`, etc.) to separate them from binary payload streams (`cab1.cab`, icons).
const table_prefix: u16 = 0x4840;

/// Base code unit for a pair of 6-bit characters packed into 12 bits (`0x3800..0x47FF`).
const pair_base: u16 = 0x3800;

/// Base code unit for a single trailing 6-bit character (`0x4800..0x483F`).
const single_base: u16 = 0x4800;

/// Maps an ASCII byte in the MSI 64-character stream alphabet (`0-9`, `A-Z`,
/// `a-z`, `.`, `_`) to its 6-bit index `0..63`, or returns `null` if `c` is
/// outside the alphabet.
fn sixBit(c: u8) ?u6 {
    return switch (c) {
        '0'...'9' => @intCast(c - '0'),
        'A'...'Z' => @intCast(c - 'A' + 10),
        'a'...'z' => @intCast(c - 'a' + 36),
        '.' => 62,
        '_' => 63,
        else => null,
    };
}

/// Encodes an ASCII MSI stream `name` into a newly allocated UTF-16LE slice
/// suitable for use as a CFBF directory entry name, returning
/// `error.InvalidStreamName` if `name` contains characters outside `[0-9A-Za-z._]`.
///
/// When `is_table` is `true`, prepends the `U+4840` table marker required by
/// Windows Installer for relational table and metadata streams (`_Tables`,
/// `_Columns`, `_StringPool`, `_StringData`, and user tables). Pass `false` for
/// embedded binary streams such as cabinets (`cab1.cab`) and icons (`Icon.*`).
///
/// Caller owns the returned slice, allocated from `allocator`.
pub fn encode(allocator: Allocator, name: []const u8, is_table: bool) ![]u16 {
    var units: std.ArrayList(u16) = .empty;
    errdefer units.deinit(allocator);
    if (is_table) try units.append(allocator, table_prefix);

    var i: usize = 0;
    while (i < name.len) {
        const first = sixBit(name[i]) orelse return error.InvalidStreamName;
        if (i + 1 < name.len) {
            const second = sixBit(name[i + 1]) orelse return error.InvalidStreamName;
            try units.append(allocator, pair_base + (@as(u16, second) << 6) + first);
            i += 2;
        } else {
            try units.append(allocator, single_base + first);
            i += 1;
        }
    }
    return units.toOwnedSlice(allocator);
}

test "table and plain names encode as Windows Installer expects" {
    const allocator = std.testing.allocator;
    const cases = [_]struct { []const u8, bool, []const u16 }{
        .{ "_Tables", true, &.{ 0x4840, 0x3f7f, 0x4164, 0x422f, 0x4836 } },
        .{ "_Columns", true, &.{ 0x4840, 0x3b3f, 0x43f2, 0x4438, 0x45b1 } },
        .{ "a", false, &.{0x4824} },
        .{ "", false, &.{} },
    };
    for (cases) |c| {
        const encoded = try encode(allocator, c[0], c[1]);
        defer allocator.free(encoded);
        try std.testing.expectEqualSlices(u16, c[2], encoded);
    }
}

test "names outside the supported alphabet are rejected" {
    const allocator = std.testing.allocator;
    try std.testing.expectError(error.InvalidStreamName, encode(allocator, "a-b", false));
    try std.testing.expectError(error.InvalidStreamName, encode(allocator, "é", false));
}
